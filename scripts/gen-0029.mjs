#!/usr/bin/env node
/**
 * Generates migration 0029 from the LIVE get_promotion prosrc dump.
 *
 * Owner decision 2026-10-24 (Phase 10 UAT): Início is the guild's LANDING
 * page — visible to visitors who are not logged in and to logged-in members
 * alike (reverses the 2026-10-20 "public visitor homepage deferred" decision).
 * The showcase must therefore be readable without a session.
 *
 * Two things are generated from the live body, never hand-copied:
 *
 * 1. get_promotion_public() — the live member body with ONLY the member gate
 *    removed. Same CTEs, same ordering, same closed field list.
 * 2. get_promotion() — the live member body with `photo_path` RESTORED. The
 *    0026 hand-written hotfix silently dropped the 07.2 round-7 photo field,
 *    so showcase cards have been falling back to class portraits since.
 *
 * Input:  .planning/tmp/live-get_promotion.sql  (dumped by scripts/rpc-ovr-audit.mjs)
 * Output: supabase/migrations/0029_public_promotion_landing.sql
 *
 * Usage: node scripts/gen-0029.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = '.planning/tmp/live-get_promotion.sql'
const OUT = 'supabase/migrations/0029_public_promotion_landing.sql'

const live = readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n')

// ---------------------------------------------------------------------------
// 1. Restore the photo field dropped by the 0026 hotfix.
//    Shape copied verbatim from 0014:1698 (round 7), which is what
//    PromotionCard expects: `card-photos/<member_id>/card.jpg`.
// ---------------------------------------------------------------------------
const OVR_FIELD = "                 'ovr', t.ovr,\n"
const PHOTO_FIELD =
  "                 'photo_path', 'card-photos/' || t.id::text || '/card.jpg',\n"
const ovrCount = live.split(OVR_FIELD).length - 1
if (ovrCount !== 1) {
  console.error(`[gen-0029] expected exactly 1 "'ovr', t.ovr," line, found ${ovrCount} — refusing to guess`)
  process.exit(1)
}
const withPhoto = live.replace(OVR_FIELD, OVR_FIELD + PHOTO_FIELD)

// ---------------------------------------------------------------------------
// 2. Strip the member gate for the public twin:
//   declare v_member uuid;
//   begin
//     v_member := (auth.jwt()->>'member_id')::uuid;
//     if v_member is null then raise exception 'no_member_claim'; end if;
//     if not exists (... m.active) then raise exception 'forbidden'; end if;
//   return ( ... )
// becomes
//   begin
//   return ( ... )
// ---------------------------------------------------------------------------
const GATE = /\ndeclare\n[\s\S]*?raise exception 'forbidden';\n  end if;\n\n  return \(/
if (!GATE.test(withPhoto)) {
  console.error('[gen-0029] member gate not found in the live dump — refusing to guess')
  process.exit(1)
}
const publicBody = withPhoto.replace(GATE, '\nbegin\n  return (')

if (publicBody.includes('auth.jwt()')) {
  console.error('[gen-0029] public body still references auth.jwt() — gate removal incomplete')
  process.exit(1)
}
if (!publicBody.trimEnd().endsWith('end;') || !withPhoto.trimEnd().endsWith('end;')) {
  console.error('[gen-0029] body does not end with "end;" — dump looks truncated')
  process.exit(1)
}
if (!withPhoto.includes("'photo_path'")) {
  console.error('[gen-0029] photo_path restore failed')
  process.exit(1)
}

const sql = `-- NeoFoot migration 0029: public Início landing (showcase readable without a session).
--
-- Owner decision 2026-10-24 (Phase 10 UAT test 8 follow-up): "Destaques and
-- Inicio were supposed to be the same page - a page that can be seen when a
-- visitor arrives and also visible to logged in users - this is why its called
-- inicio, its a landing page." This REVERSES the 2026-10-20 decision that
-- deferred the public visitor homepage (ROADMAP Phase 10 criterion 4,
-- 10-CONTEXT and the Destaques header comment are updated in the same change).
--
-- Generated by scripts/gen-0029.mjs from the LIVE pg_proc.prosrc dump
-- (.planning/tmp/live-get_promotion.sql, re-dumped AFTER 0028). Never hand-edit
-- the function bodies: 08-01 proved hand-copied bodies drift from live and
-- silently change rank math.
--
-- Three server-side pieces, all required for a real public landing:
--
-- 1. get_promotion() — unchanged logic, but photo_path is RESTORED. The 0026
--    hand-written hotfix (alias repair) rebuilt the body without the 07.2
--    round-7 photo field, so every showcase card has silently fallen back to
--    the class portrait. This puts the member photo back on the card payload.
--    The member gate stays exactly as it is: anon still cannot call it.
--
-- 2. get_promotion_public() — the same body with NO member gate. Byte-identical
--    to get_promotion apart from the gate: same CTEs, same class/function
--    cohorts, same top-5-per-class ordering, same closed highlight field list
--    {stat_key,label,label_short,value_type,value,points}. Key-stat CONFIG
--    (weights/toggles/selection_order) still has no representation anywhere in
--    the payload (RNK-02 / 07.2 D-13 unchanged).
--
-- 3. card-photos anon read policy — the showcase renders the member's
--    submitted screenshot. The bucket stays PRIVATE (no public URL); anon may
--    read an object only when its top-level folder is an ACTIVE member id,
--    which is exactly the path the showcase payload carries. Writes stay
--    authenticated-only and own-folder-only (card-photos-storage.sql).
--
-- Threat notes: the public payload exposes in-game identity (display_name),
-- class/function, OVR, the 6 key stats and the card photo of the top-5 per
-- class. That is the owner's deliberate showcase decision. No Discord handle,
-- no role, no member UUID except inside the photo path (required to fetch the
-- photo), no key-stat config, no aggregate internals.

-- ---------------------------------------------------------------------------
-- 1. Member showcase RPC — photo_path restored (0026 regression).
-- ---------------------------------------------------------------------------
create or replace function public.get_promotion()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
${withPhoto}$$;

comment on function public.get_promotion() is
  'Members-only showcase (0014 + 0028 + 0029): per class, top-5-by-OVR cards whose highlights are the class''s KEY STATS with the closed field list {stat_key,label,label_short,value_type,value,points}. photo_path is the member card-photos object key. Key-stat CONFIG is never serialised.';

revoke all on function public.get_promotion() from public;
grant execute on function public.get_promotion() to authenticated;

-- ---------------------------------------------------------------------------
-- 2. Public showcase RPC — identical body, member gate removed.
-- ---------------------------------------------------------------------------
create or replace function public.get_promotion_public()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
${publicBody}$$;

comment on function public.get_promotion_public() is
  'Public landing showcase (owner decision 2026-10-24): identical body to get_promotion with the member gate removed - anon-callable, active members only in the data. Same closed field list; key-stat CONFIG is never serialised.';

revoke all on function public.get_promotion_public() from public;
grant execute on function public.get_promotion_public() to anon, authenticated;

-- ---------------------------------------------------------------------------
-- 3. Storage: anon may read ACTIVE members' card photos (the showcase photo).
--    The policy cannot read public.members directly: storage RLS evaluates as
--    the requesting role and anon has no grant on that table (proven live:
--    403 "permission denied for table members"). A SECURITY DEFINER predicate
--    answers the same question without widening anon's grants.
-- ---------------------------------------------------------------------------
create or replace function public.is_public_card_photo(object_name text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from members m
    where m.id::text = (storage.foldername(object_name))[1]
      and m.active
  );
$$;

comment on function public.is_public_card_photo(text) is
  'Storage RLS predicate (0029): true when the card-photos object key is <active-member-id>/card.jpg. SECURITY DEFINER so the storage policy does not need an anon grant on members; returns a boolean only, never member data.';

revoke all on function public.is_public_card_photo(text) from public;
grant execute on function public.is_public_card_photo(text) to anon, authenticated;

drop policy if exists "card-photos: public showcase read" on storage.objects;
create policy "card-photos: public showcase read"
  on storage.objects for select to anon
  using (
    bucket_id = 'card-photos'
    and public.is_public_card_photo(name)
  );

insert into supabase_migrations.schema_migrations (version, name, statements)
values ('0029', 'public_promotion_landing', null)
on conflict (version) do nothing;

commit;
`

writeFileSync(OUT, sql, 'utf8')
console.log(`wrote ${OUT}`)
console.log(`  member body: ${withPhoto.split('\n').length} lines (photo_path restored)`)
console.log(`  public body: ${publicBody.split('\n').length} lines (gate removed, no auth.jwt() left)`)
